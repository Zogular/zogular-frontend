type CapabilityInput = Omit<
  AdminCapabilityDefinition,
  "version" | "authorizationAuthority"
>;

function defineCapability(input: CapabilityInput): AdminCapabilityDefinition {
  const parsed = AdminCapabilityDefinitionSchema.parse({
    ...input,
    version: ADMIN_CAPABILITY_CONTRACT_VERSION,
    authorizationAuthority: "backend",
  });

  Object.freeze(parsed.frontendPermissionHints);
  Object.freeze(parsed.backendPermissionEvidence.permissions);
  Object.freeze(parsed.backendPermissionEvidence);
  Object.freeze(parsed.backendDependency);
  Object.freeze(parsed.blockers);
  return Object.freeze(parsed);
}

