function assertRegistryInvariants(capabilities: readonly AdminCapabilityDefinition[]): void {
  const ids = capabilities.map((capability) => capability.id);
  const routes = capabilities
    .map((capability) => capability.currentRoute)
    .filter((route): route is string => route !== null);
  const configuredGroups = new Set<AdminCapabilityGroupId>(ADMIN_CAPABILITY_GROUPS.map((group) => group.id));

  if (capabilities.length !== ADMIN_CAPABILITY_IDS.length || new Set(ids).size !== ids.length) {
    throw new Error("Admin capability registry IDs are incomplete or duplicated.");
  }
  if (ADMIN_CAPABILITY_IDS.some((id) => !ids.includes(id))) {
    throw new Error("Admin capability registry is missing a documented destination.");
  }
  if (new Set(routes).size !== routes.length) {
    throw new Error("Admin capability registry routes must be unique.");
  }
  if (capabilities.some((capability) => !configuredGroups.has(capability.groupId))) {
    throw new Error("Admin capability registry references an unknown group.");
  }
}

assertRegistryInvariants(registry);

